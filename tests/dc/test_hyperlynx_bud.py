# Shaped as the issue's example: the sections KiPI reads among ones it leaves alone.
BUD = """\
{BUD} WARNING: Do not edit this file! It is re-written automatically by BoardSim.
{VERSION=2.200}
{STACKUP
(SIGNAL R?=YES COL=FF T=4.73202e-05 P=0 W=1.50876e-04 L=F.Cu M=Metal)
}
{SUPPLIES
(S NAME=VIN VAL=12 V?=NO C?=NO)
(S NAME=+3V3 VAL=3.3 V?=NO C?=NO)
(S NAME=GND VAL=0 V?=NO C?=NO)
(S NAME=+5V_GONE VAL=5 V?=NO C?=NO)
}
{DC_CONN
(REF_DES=U1 PIN1=1 PIN2=2 RDC=0.01)
(REF_DES=FB9 PIN1=1 PIN2=2 RDC=0.1)
}
{NET_RULES
(R C = "(All)" MIN_DELAY=-5.00000e-09 MAX_DELAY=1.00000e-06 STIMULUS=OSC)
}
{TEMPERATURE=2.000000e+01}
{DCCGROUPS
(G NAME=Group1)
(G NAME=Group2)
(G NAME=Empty)
}
{DCCAPACITORS
(C REFDES=C1 DCCGROUP=Group1)
(C REFDES=C2 DCCGROUP=Group1)
(C REFDES=C3 DCCGROUP=Group2)
(C REFDES=C4 DCCGROUP=Group2)
(C REFDES=C99 DCCGROUP=Group2)
}
{PI_VRM
(V REFDES=U1 NAME=whatever)
}
{PI_SIGNAL_SOURCES
}
{END}
"""


def _board():
    snap = board()
    values = {"C1": "100nF 16V X7R", "C2": "100nF 16V X7R", "C3": "10uF", "C4": "4.7uF"}
    for i, (ref, value) in enumerate(values.items()):
        x = 14 + 2 * i
        snap.pads += [pad(f"{ref}_1", "+3V3", ref, "1", box(x, 0, x + 0.5, 0.5)),
                      pad(f"{ref}_2", "GND", ref, "2", box(x, 0.5, x + 0.5, 1))]
        snap.footprints.append(Footprint(ref, ref, value, (x, 0.5), "top"))
    return snap


@pytest.fixture
def bud(tmp_path):
    path = tmp_path / "board.bud"
    path.write_text(BUD, encoding="utf-8")
    return path


def test_sections_hold_their_records_and_one_liners_hold_none():
    s = sections(BUD)
    assert s["BUD"] == [] and s["VERSION"] == [] and s["PI_SIGNAL_SOURCES"] == []
    assert s["SUPPLIES"][1] == {"NAME": "+3V3", "VAL": "3.3", "V?": "NO", "C?": "NO"}
    assert s["DC_CONN"][0] == {"REF_DES": "U1", "PIN1": "1", "PIN2": "2", "RDC": "0.01"}


def test_power_nets_series_links_and_capacitor_groups_are_read(bud):
    base = setup("ldo")
    base.links = []
    out, notes, nets = import_bud(bud, _board(), base)
    assert nets == ["VIN", "+3V3", "GND"]
    assert any("+5V_GONE" in n for n in notes)
    assert out.links == [DcLink("U1", PinRef("U1", "VIN", ["1"]), PinRef("U1", "+3V3", ["2"]),
                                0.01)]
    assert any(n.startswith("FB9") for n in notes)
    # VRMs and loads are left as they were; the VRM section is named, not guessed at.
    assert [v.name for v in out.vrms] == ["J1", "U1"] and len(out.loads) == 1
    assert any("PI_VRM" in n for n in notes)
    caps = {m.name: m for m in out.caps}
    assert set(caps) == {"Group1", "Group2"}
    assert caps["Group1"].refs == ["C1", "C2"]
    assert caps["Group1"].capacitance_f == pytest.approx(100e-9)
    assert (caps["Group1"].rated_v, caps["Group1"].dielectric) == (16.0, "X7R")
    assert caps["Group2"].capacitance_f == 0.0            # 10 µF and 4.7 µF: left to fill
    assert any("Group2" in n and "one value" in n for n in notes)
    assert any("C99" in n for n in notes) and any("Empty" in n for n in notes)
    assert base.caps == [] and base.links == []           # the setup given is not changed


def test_an_import_merges_into_what_is_there(bud):
    base = setup("ldo")
    base.links = [DcLink("old U1", PinRef("U1", "VIN", ["1"]), PinRef("U1", "+3V3", ["2"]),
                         1.0)]
    base.caps = [CapModel("Group1", 1e-6, 1e-9, 0.01, ["C9"]),
                 CapModel("Mine", 1e-6, 1e-9, 0.01, ["C3", "C8"])]
    out, notes, _ = import_bud(bud, _board(), base)
    assert [(k.name, k.resistance) for k in out.links] == [("U1", 0.01)]
    caps = {m.name: m for m in out.caps}
    assert caps["Group1"].refs == ["C1", "C2"]
    assert caps["Group1"].capacitance_f == 1e-6           # its own values are kept
    assert caps["Mine"].refs == ["C8"] and caps["Group2"].refs == ["C3", "C4"]
    assert any("Moved" in n and "C3" in n for n in notes)


def test_a_file_that_is_not_a_session_file_is_refused(tmp_path):
    path = tmp_path / "x.bud"
    path.write_text("{SUPPLIES\n}\n", encoding="utf-8")
    with pytest.raises(BudImportError):
        import_bud(path, board())
